       TRANSACTION_DATE,
       AMOUNT,
       MERCHANT,
       LOCATION,
       FRAUD_FLAG
FROM CARD_TRANSACTIONS;
SELECT FRAUD_FLAG,
       COUNT(*) AS TRANSACTION_COUNT,
       SUM(AMOUNT) AS TOTAL_AMOUNT
FROM CARD_TRANSACTIONS
GROUP BY FRAUD_FLAG;

SELECT MERCHANT,
       AVG(AMOUNT) AS AVERAGE_SPENDING,
       SUM(AMOUNT) AS TOTAL_SPENDING
FROM CARD_TRANSACTIONS
GROUP BY MERCHANT;
SELECT TRANSACTION_ID,
       CUSTOMER_ID,
       AMOUNT,
       MERCHANT,
       LOCATION,
       FRAUD_FLAG
FROM CARD_TRANSACTIONS
