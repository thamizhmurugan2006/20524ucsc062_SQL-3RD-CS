SELECT TRANSACTION_ID,
       CUSTOMER_ID,
       TRANSACTION_DATE,
       AMOUNT,
       MERCHANT,
       LOCATION,
       FRAUD_FLAG
FROM CARD_TRANSACTIONS;
SELECT FRAUD_FLAG,
       COUNT(*) AS TRANSACTION_COUNT,
       SUM(AMOUNT) AS TOTAL_AMOUNT
FROM CARD_TRANSACTIONS
GROUP BY FRAUD_FLAG;
SELECT *
FROM CARD_TRANSACTIONS
WHERE AMOUNT > 50000;
SELECT MERCHANT,
       COUNT(*) AS TRANSACTION_COUNT,
       SUM(AMOUNT) AS TOTAL_SPENDING
FROM CARD_TRANSACTIONS
GROUP BY MERCHANT;
